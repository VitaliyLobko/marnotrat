const parts = (v) => v.split('.').map(Number);
const newer = (a, b) => {
  const [x, y] = [parts(a), parts(b)];
  for (let i = 0; i < Math.max(x.length, y.length); i += 1) {
    if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) > (y[i] ?? 0);
  }
  return false;
};

/** Записи новіші за seen і не новіші за current. */
export const changesSince = (seen, current) => CHANGES.filter((c) => newer(c.v, seen) && !newer(c.v, current));
